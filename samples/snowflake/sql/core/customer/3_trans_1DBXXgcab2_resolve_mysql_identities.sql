-- Beyond Entity trans_1DBXXgcab2  |  proc_j3HyTdoXBh "Resolve Customer Identity"  |  order 3
-- RAW_SUPPORT_TICKETS -> CUSTOMER_IDENTITY_MAP. Confidence 0.95: the support system does not
-- own the customer record and a ticket contact email may be a colleague or shared mailbox.
INSERT INTO CUSTOMER_IDENTITY_MAP (ENTERPRISE_CUSTOMER_KEY, SOURCE_SYSTEM, SOURCE_CUSTOMER_REF, EMAIL_NORMALIZED, EMAIL_HASH, MATCH_METHOD, MATCH_CONFIDENCE, RESOLVED_AT, IS_ACTIVE)
SELECT MD5(LOWER(TRIM(st.CONTACT_EMAIL))), st._SOURCE_SYSTEM, st.SUPPORT_CUSTOMER_REF, LOWER(TRIM(st.CONTACT_EMAIL)), SHA2(LOWER(TRIM(st.CONTACT_EMAIL)), 256), 'EMAIL_NORMALIZED', 0.95, CURRENT_TIMESTAMP(), TRUE
FROM RAW_SUPPORT_TICKETS st
WHERE st.CONTACT_EMAIL IS NOT NULL AND TRIM(st.CONTACT_EMAIL) <> ''
QUALIFY ROW_NUMBER() OVER (PARTITION BY st.SUPPORT_CUSTOMER_REF ORDER BY st.CREATED_AT DESC, st._INGESTED_AT DESC) = 1
