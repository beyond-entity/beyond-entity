-- RAW_CUSTOMERS -> CUSTOMER_IDENTITY_MAP. Confidence 1.0: Oracle owns the customer record.
INSERT INTO CUSTOMER_IDENTITY_MAP (ENTERPRISE_CUSTOMER_KEY, SOURCE_SYSTEM, SOURCE_CUSTOMER_REF, EMAIL_NORMALIZED, EMAIL_HASH, MATCH_METHOD, MATCH_CONFIDENCE, RESOLVED_AT, IS_ACTIVE)
SELECT MD5(LOWER(TRIM(c.EMAIL))), c._SOURCE_SYSTEM, TO_VARCHAR(c.CUSTOMER_ID), LOWER(TRIM(c.EMAIL)), SHA2(LOWER(TRIM(c.EMAIL)), 256), 'EMAIL_NORMALIZED', 1.0, CURRENT_TIMESTAMP(), TRUE
FROM RAW_CUSTOMERS c
WHERE c.EMAIL IS NOT NULL AND TRIM(c.EMAIL) <> ''
QUALIFY ROW_NUMBER() OVER (PARTITION BY c.CUSTOMER_ID ORDER BY c.UPDATED_AT DESC, c._INGESTED_AT DESC) = 1
