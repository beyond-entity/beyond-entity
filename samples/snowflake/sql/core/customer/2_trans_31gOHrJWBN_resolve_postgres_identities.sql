-- Beyond Entity trans_31gOHrJWBN  |  proc_j3HyTdoXBh "Resolve Customer Identity"  |  order 2
-- RAW_SUBSCRIPTIONS -> CUSTOMER_IDENTITY_MAP. Partitioned on CRM_CUSTOMER_REF: one customer
-- can hold several subscriptions, so the subscription key would emit one row per subscription.
INSERT INTO CUSTOMER_IDENTITY_MAP (ENTERPRISE_CUSTOMER_KEY, SOURCE_SYSTEM, SOURCE_CUSTOMER_REF, EMAIL_NORMALIZED, EMAIL_HASH, MATCH_METHOD, MATCH_CONFIDENCE, RESOLVED_AT, IS_ACTIVE)
SELECT MD5(LOWER(TRIM(s.BILLING_EMAIL))), s._SOURCE_SYSTEM, s.CRM_CUSTOMER_REF, LOWER(TRIM(s.BILLING_EMAIL)), SHA2(LOWER(TRIM(s.BILLING_EMAIL)), 256), 'EMAIL_NORMALIZED', 1.0, CURRENT_TIMESTAMP(), TRUE
FROM RAW_SUBSCRIPTIONS s
WHERE s.BILLING_EMAIL IS NOT NULL AND TRIM(s.BILLING_EMAIL) <> ''
QUALIFY ROW_NUMBER() OVER (PARTITION BY s.CRM_CUSTOMER_REF ORDER BY s.UPDATED_AT DESC, s._INGESTED_AT DESC) = 1
